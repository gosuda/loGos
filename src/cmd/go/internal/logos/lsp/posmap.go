package lsp

import (
	"bytes"
	"fmt"
)

// EditMapVersion is the only edit map version this package reads. The
// compiler writes version 2 maps, whose Segments array tells copied bytes
// from generated ones; the Edits array stays for the size arithmetic only.
const EditMapVersion = 2

// EditSpan is one applied edit of a lowering: the bytes of the original
// text from Start up to End became Len bytes of the lowered text. The
// position map checks them for the size arithmetic; every origin decision
// goes through Segments.
type EditSpan struct {
	Start int `json:"start"`
	End   int `json:"end"`
	Len   int `json:"len"`
}

// Segment is one run of the lowered text: the Len bytes at Out are a
// verbatim copy of the Len bytes of the original text at Orig, or, with
// Orig negative, compiler-generated. The segments of one edit map
// partition [0, Out) of the lowered text in order.
type Segment struct {
	Out  int `json:"out"`
	Len  int `json:"len"`
	Orig int `json:"orig"` // -1 marks generated bytes
}

// EditMap is the JSON document the compiler writes beside each lowered
// file (cmd/compile/internal/logos.EditMap). Size and Out are the byte
// sizes of the original and lowered texts.
type EditMap struct {
	Version  int        `json:"version"`
	Source   string     `json:"source"`
	Size     int        `json:"size"`
	Out      int        `json:"out"`
	Edits    []EditSpan `json:"edits"`
	Segments []Segment  `json:"segments"`
}

// edge says which side of an insertion a boundary offset belongs to. A
// leading offset is the start of a token, and sits after text inserted at
// that offset; a trailing offset is the end of a token, and sits before it.
type edge int

const (
	leading edge = iota
	trailing
)

// posMap translates positions between an original loGo/s text and its
// lowered Go text. It rests on the segments of the lowering, which mark
// the bytes the lowering copied unchanged, so the operand of a ?
// statement, say, still maps exactly.
type posMap struct {
	orig, low *text
	segs      []Segment
}

// newPosMap checks m against the two texts and builds the map.
func newPosMap(src, out []byte, m EditMap) (*posMap, error) {
	if err := checkEditMap(src, out, m); err != nil {
		return nil, err
	}
	return &posMap{orig: newText(src), low: newText(out), segs: m.Segments}, nil
}

// checkEditMap rejects a map that cannot describe the transformation from
// src to out: another version, other sizes, edits that are unordered,
// overlap, leave the text, or do not add up to the lowered size, or
// segments that do not partition the lowered text, leave the source, or
// disagree with the texts they claim to copy.
func checkEditMap(src, out []byte, m EditMap) error {
	if m.Version != EditMapVersion {
		return fmt.Errorf("edit map for %s has unsupported version %d", m.Source, m.Version)
	}
	if m.Size != len(src) || m.Out != len(out) {
		return fmt.Errorf("edit map for %s does not match its texts", m.Source)
	}
	prev, delta := 0, 0
	for _, s := range m.Edits {
		if !s.fits(prev, len(src)) {
			return fmt.Errorf("edit map for %s holds the invalid span %d:%d", m.Source, s.Start, s.End)
		}
		prev = s.End
		delta += s.Len - (s.End - s.Start)
	}
	if len(src)+delta != len(out) {
		return fmt.Errorf("edit map for %s does not add up to the lowered size", m.Source)
	}
	next := 0
	for _, s := range m.Segments {
		if s.Len <= 0 || s.Out != next {
			return fmt.Errorf("edit map for %s has segments that do not partition the lowered text", m.Source)
		}
		if s.Len > len(out)-s.Out {
			return fmt.Errorf("edit map for %s has segments that do not cover the lowered text", m.Source)
		}
		end := s.Out + s.Len
		if s.Orig < -1 {
			return fmt.Errorf("edit map for %s holds the invalid segment %d:%d", m.Source, s.Out, end)
		}
		if s.Orig >= 0 {
			if s.Len > len(src)-s.Orig {
				return fmt.Errorf("edit map for %s holds the copy segment %d:%d outside its source", m.Source, s.Out, end)
			}
			if !bytes.Equal(src[s.Orig:s.Orig+s.Len], out[s.Out:end]) {
				return fmt.Errorf("edit map for %s holds the copy segment %d:%d that differs from its source", m.Source, s.Out, end)
			}
		}
		next = end
	}
	if next != len(out) {
		return fmt.Errorf("edit map for %s has segments that do not cover the lowered text", m.Source)
	}
	return nil
}

// fits reports whether s starts at or after prev, the end of the span
// before it, ends inside a text of size bytes, and does not start after it
// ends.
func (s EditSpan) fits(prev, size int) bool {
	return s.Start >= prev && s.End >= s.Start && s.End <= size && s.Len >= 0
}

// lowOffset maps an offset of the original text to the lowered text. It
// reports false when o lies in text the lowering deleted: a deleted offset
// has no lowered position of its own. At a seam the side of e decides:
// the trailing edge stays before text inserted at o and the leading edge
// goes after it, unless the inserted text replaces deleted bytes, in which
// case both edges stay before it.
func (m *posMap) lowOffset(o int, e edge) (int, bool) {
	if len(m.orig.data) == 0 && o == 0 {
		// An empty source with generated output is one insertion
		// at offset zero: the trailing edge stays before it and
		// the leading edge goes after it.
		if e == trailing {
			return 0, true
		}
		return len(m.low.data), true
	}
	if o == 0 && e == trailing {
		// A generated prefix is an insertion at the start of the
		// text: the trailing edge stays before it.
		for _, s := range m.segs {
			if s.Orig >= 0 {
				if s.Orig == 0 && s.Out > 0 {
					return 0, true
				}
				break
			}
		}
	}
	for i, s := range m.segs {
		if s.Orig < 0 {
			continue
		}
		if o >= s.Orig && o < s.Orig+s.Len {
			return s.Out + o - s.Orig, true
		}
		if o != s.Orig+s.Len {
			continue
		}
		if e == trailing {
			return s.Out + s.Len, true
		}
		if i+1 < len(m.segs) && m.segs[i+1].Orig < 0 {
			g := m.segs[i+1]
			pure := (i+2 >= len(m.segs) && o == len(m.orig.data)) ||
				(i+2 < len(m.segs) && m.segs[i+2].Orig == o)
			if pure {
				return g.Out + g.Len, true
			}
		}
		return s.Out + s.Len, true
	}
	return 0, false
}

// lowOffsetNear maps an offset of deleted original text the way lowOffset
// maps a seam: the leading edge sits at the end of the nearest copied text
// before o in the original, where its replacement starts, and the trailing
// edge sits at the start of the nearest copied text after o. It compares
// original offsets, not lowered ones: a lowering may move or duplicate
// exact chunks, so lowered order need not follow original order.
func (m *posMap) lowOffsetNear(o int, e edge) int {
	if v, ok := m.lowOffset(o, e); ok {
		return v
	}
	if e == trailing {
		bestOrig := -1
		bestOut := len(m.low.data)
		for _, s := range m.segs {
			if s.Orig < 0 || s.Orig <= o {
				continue
			}
			if bestOrig == -1 || s.Orig < bestOrig || (s.Orig == bestOrig && s.Out < bestOut) {
				bestOrig = s.Orig
				bestOut = s.Out
			}
		}
		return bestOut
	}
	bestEnd := -1
	bestOut := 0
	for _, s := range m.segs {
		if s.Orig < 0 {
			continue
		}
		end := s.Orig + s.Len
		if end > o {
			continue
		}
		outEnd := s.Out + s.Len
		if bestEnd == -1 || end > bestEnd || (end == bestEnd && outEnd < bestOut) {
			bestEnd = end
			bestOut = outEnd
		}
	}
	return bestOut
}

// genAnchors returns the original span a generated run stands for: it runs
// from the end of the preceding copied text, prevEnd, to the start of the
// next copied text.
func (m *posMap) genAnchors(i, prevEnd int) (start, end int) {
	start, end = prevEnd, len(m.orig.data)
	for _, s := range m.segs[i+1:] {
		if s.Orig >= 0 {
			end = s.Orig
			break
		}
	}
	return start, end
}

// origOffset maps an offset of the lowered text to the original text. The
// second result reports whether o lies strictly inside generated text: a
// boundary offset, including the end of the text, counts as the user's own
// text. A generated offset still maps to the original text that produced
// it, the start of it on the leading edge and the end of it on the
// trailing edge. At the seam of a deletion, the trailing edge stays before
// the deleted text and the leading edge goes after it.
func (m *posMap) origOffset(o int, e edge) (int, bool) {
	if o == len(m.low.data) && len(m.segs) > 0 {
		// The end of the lowered text is a boundary, never
		// generated text.
		last := m.segs[len(m.segs)-1]
		if last.Orig < 0 {
			return len(m.orig.data), false
		}
		if end := last.Orig + last.Len; end == len(m.orig.data) {
			return end, false
		} else if e == trailing {
			return end, false
		} else {
			return len(m.orig.data), false
		}
	}
	prevEnd := 0
	for i, s := range m.segs {
		end := s.Out + s.Len
		if o < s.Out || o >= end {
			if s.Orig >= 0 {
				prevEnd = s.Orig + s.Len
			}
			continue
		}
		if s.Orig >= 0 {
			if o == s.Out && s.Orig > prevEnd && e == trailing {
				return prevEnd, false
			}
			return s.Orig + o - s.Out, false
		}
		if o == s.Out {
			return prevEnd, false
		}
		start, finish := m.genAnchors(i, prevEnd)
		if e == trailing {
			return finish, true
		}
		return start, true
	}
	return len(m.orig.data), false
}

// toLowered maps a position of the original text to the lowered text. A
// position inside deleted text maps to the start of what replaced it.
func (m *posMap) toLowered(p Position) Position {
	o := m.orig.offset(p)
	if v, ok := m.lowOffset(o, leading); ok {
		return m.low.position(v)
	}
	return m.low.position(m.lowOffsetNear(o, leading))
}

// toOriginal maps a position of the lowered text to the original text. A
// position inside generated text maps to the original text that produced
// it.
func (m *posMap) toOriginal(p Position) Position {
	o, _ := m.origOffset(m.low.offset(p), leading)
	return m.orig.position(o)
}

// rangeToLowered maps a range of the original text to the lowered text. It
// stays tight: the start sits after text inserted at its offset and the end
// before text inserted at its offset.
func (m *posMap) rangeToLowered(r Range) Range {
	start := m.lowOffsetNear(m.orig.offset(r.Start), leading)
	end := max(start, m.lowOffsetNear(m.orig.offset(r.End), trailing))
	return Range{Start: m.low.position(start), End: m.low.position(end)}
}

// rangeToOriginal maps a range of the lowered text to the original text. A
// range that touches generated text widens to the original text that
// produced it: every generated run the range overlaps contributes its
// anchor, so a highlight over the ? expansion maps to the ? token even
// when its end sits exactly on the generated-to-copy seam.
func (m *posMap) rangeToOriginal(r Range) Range {
	loStart := m.low.offset(r.Start)
	loEnd := m.low.offset(r.End)
	if loEnd < loStart {
		loEnd = loStart
	}
	start, _ := m.origOffset(loStart, leading)
	end, _ := m.origOffset(loEnd, trailing)
	if loStart < loEnd {
		start, end = m.widenOverGenerated(loStart, loEnd, start, end)
	}
	end = max(start, end)
	return Range{Start: m.orig.position(start), End: m.orig.position(end)}
}

// widenOverGenerated expands start and end to the anchors of every
// generated run overlapping [loStart, loEnd). Anchors that run backwards
// belong to generated text between moved copies and stay out: widening to
// them would claim almost the whole original text.
func (m *posMap) widenOverGenerated(loStart, loEnd, start, end int) (int, int) {
	prevEnd := 0
	for i, s := range m.segs {
		segEnd := s.Out + s.Len
		if s.Orig >= 0 {
			prevEnd = s.Orig + s.Len
			continue
		}
		if s.Out >= loEnd || segEnd <= loStart {
			continue
		}
		aStart, aFinish := m.genAnchors(i, prevEnd)
		if aStart > aFinish {
			continue
		}
		start = min(start, aStart)
		end = max(end, aFinish)
	}
	return start, end
}
